CREATE TABLE salts (
    day date PRIMARY KEY,
    salt bytea NOT NULL CHECK (octet_length(salt) = 32),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE dict (
    kind smallint NOT NULL,
    id integer GENERATED BY DEFAULT AS IDENTITY,
    value text NOT NULL,
    PRIMARY KEY (kind, id),
    UNIQUE (kind, value)
);

CREATE TABLE day_close (
    site_id integer NOT NULL,
    day date NOT NULL,
    status text NOT NULL,
    version integer NOT NULL DEFAULT 0,
    closed_at timestamptz,
    rows bigint NOT NULL DEFAULT 0,
    duration_ms bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (site_id, day)
);

CREATE TABLE dirty_day (
    site_id integer NOT NULL,
    day date NOT NULL,
    reason text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (site_id, day)
);

CREATE TABLE events (
    site_id integer NOT NULL,
    retention_class smallint NOT NULL,
    local_day date,
    ts timestamptz NOT NULL,
    visitor_id bigint NOT NULL,
    session_id bigint NOT NULL,
    kind smallint NOT NULL,
    name_id integer NOT NULL DEFAULT 0,
    path_id integer NOT NULL DEFAULT 0,
    referrer_id integer NOT NULL DEFAULT 0,
    source_id integer NOT NULL DEFAULT 0,
    medium_id integer NOT NULL DEFAULT 0,
    campaign_id integer NOT NULL DEFAULT 0,
    utm_content_id integer NOT NULL DEFAULT 0,
    utm_term_id integer NOT NULL DEFAULT 0,
    country character(2) NOT NULL DEFAULT '',
    browser_id integer NOT NULL DEFAULT 0,
    os_id integer NOT NULL DEFAULT 0,
    device smallint NOT NULL DEFAULT 0,
    screen smallint NOT NULL DEFAULT 0,
    engagement_ms integer NOT NULL DEFAULT 0,
    scroll_pct smallint NOT NULL DEFAULT 0,
    props jsonb,
    CHECK (retention_class IN (0, 7, 30, 90, 365))
) PARTITION BY LIST (retention_class);

CREATE TABLE events_r7 PARTITION OF events FOR VALUES IN (7) PARTITION BY RANGE (ts);
CREATE TABLE events_r30 PARTITION OF events FOR VALUES IN (30) PARTITION BY RANGE (ts);
CREATE TABLE events_r90 PARTITION OF events FOR VALUES IN (90) PARTITION BY RANGE (ts);
CREATE TABLE events_r365 PARTITION OF events FOR VALUES IN (365) PARTITION BY RANGE (ts);
CREATE TABLE events_rf PARTITION OF events FOR VALUES IN (0) PARTITION BY RANGE (ts);

CREATE INDEX events_ts_brin ON events USING brin (ts)
    WITH (pages_per_range = 32, autosummarize = on);
CREATE INDEX events_custom ON events (site_id, ts) WHERE kind = 1;

CREATE TABLE sessions (
    site_id integer NOT NULL,
    retention_class smallint NOT NULL,
    session_id bigint NOT NULL,
    visitor_id bigint NOT NULL,
    start timestamptz NOT NULL,
    last timestamptz NOT NULL,
    local_day date NOT NULL,
    entry_path integer NOT NULL DEFAULT 0,
    exit_path integer NOT NULL DEFAULT 0,
    source_id integer NOT NULL DEFAULT 0,
    medium_id integer NOT NULL DEFAULT 0,
    campaign_id integer NOT NULL DEFAULT 0,
    country character(2) NOT NULL DEFAULT '',
    browser_id integer NOT NULL DEFAULT 0,
    os_id integer NOT NULL DEFAULT 0,
    device smallint NOT NULL DEFAULT 0,
    pageviews integer NOT NULL DEFAULT 0,
    events integer NOT NULL DEFAULT 0,
    engagement_ms integer NOT NULL DEFAULT 0,
    bounce boolean NOT NULL DEFAULT true,
    PRIMARY KEY (site_id, start, session_id, retention_class),
    CHECK (retention_class IN (0, 7, 30, 90, 365))
) PARTITION BY LIST (retention_class);

CREATE TABLE sessions_r7 PARTITION OF sessions FOR VALUES IN (7) PARTITION BY RANGE (start);
CREATE TABLE sessions_r30 PARTITION OF sessions FOR VALUES IN (30) PARTITION BY RANGE (start);
CREATE TABLE sessions_r90 PARTITION OF sessions FOR VALUES IN (90) PARTITION BY RANGE (start);
CREATE TABLE sessions_r365 PARTITION OF sessions FOR VALUES IN (365) PARTITION BY RANGE (start);
CREATE TABLE sessions_rf PARTITION OF sessions FOR VALUES IN (0) PARTITION BY RANGE (start);
