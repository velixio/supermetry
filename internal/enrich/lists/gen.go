// Package main refreshes the public enrichment datasets embedded by Panel.
package main

//go:generate go run .

import (
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/netip"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	crawlerURL     = "https://raw.githubusercontent.com/monperrus/crawler-user-agents/master/crawler-user-agents.json"
	spamURL        = "https://raw.githubusercontent.com/matomo-org/referrer-spam-list/master/spammers.txt"
	awsURL         = "https://ip-ranges.amazonaws.com/ip-ranges.json"
	gcpURL         = "https://www.gstatic.com/ipranges/cloud.json"
	azurePage      = "https://www.microsoft.com/en-us/download/confirmation.aspx?id=56519"
	oracleURL      = "https://docs.oracle.com/en-us/iaas/tools/public_ip_ranges.json"
	cloudflare4URL = "https://www.cloudflare.com/ips-v4"
	cloudflare6URL = "https://www.cloudflare.com/ips-v6"
)

var client = &http.Client{Timeout: 2 * time.Minute}

func main() {
	must(writeCrawlerPatterns())
	must(writeURL("referrer-spam.txt", spamURL))

	prefixes, err := providerPrefixes()
	must(err)
	var text strings.Builder
	text.WriteString("# Generated by go generate ./internal/enrich/lists; do not edit.\n")
	for _, prefix := range prefixes {
		text.WriteString(prefix.String())
		text.WriteByte('\n')
	}
	must(os.WriteFile("datacenter-cidrs.txt", []byte(text.String()), 0o644))

	month := time.Now().UTC().Format("2006-01")
	dbURL := "https://download.db-ip.com/free/dbip-country-lite-" + month + ".mmdb.gz"
	must(writeGzipURL("dbip-country-lite.mmdb", dbURL))
}

func writeURL(path, source string) error {
	data, err := fetch(source)
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

func writeGzipURL(path, source string) error {
	data, err := fetch(source)
	if err != nil {
		return err
	}
	reader, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return fmt.Errorf("open %s: %w", source, err)
	}
	defer reader.Close()
	decoded, err := io.ReadAll(io.LimitReader(reader, 64<<20))
	if err != nil {
		return fmt.Errorf("decompress %s: %w", source, err)
	}
	return os.WriteFile(path, decoded, 0o644)
}

func writeCrawlerPatterns() error {
	data, err := fetch(crawlerURL)
	if err != nil {
		return err
	}
	var entries []struct {
		Pattern string `json:"pattern"`
	}
	if err := json.Unmarshal(data, &entries); err != nil {
		return fmt.Errorf("decode %s: %w", crawlerURL, err)
	}
	data, err = json.MarshalIndent(entries, "", "  ")
	if err != nil {
		return fmt.Errorf("encode crawler patterns: %w", err)
	}
	data = append(data, '\n')
	return os.WriteFile("crawler-user-agents.json", data, 0o644)
}

func fetch(source string) ([]byte, error) {
	response, err := client.Get(source)
	if err != nil {
		return nil, fmt.Errorf("fetch %s: %w", source, err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: %s", source, response.Status)
	}
	data, err := io.ReadAll(io.LimitReader(response.Body, 128<<20))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", source, err)
	}
	return data, nil
}

func providerPrefixes() ([]netip.Prefix, error) {
	var all []string

	var aws struct {
		Prefixes []struct {
			Prefix string `json:"ip_prefix"`
		} `json:"prefixes"`
		IPv6Prefixes []struct {
			Prefix string `json:"ipv6_prefix"`
		} `json:"ipv6_prefixes"`
	}
	if err := fetchJSON(awsURL, &aws); err != nil {
		return nil, err
	}
	for _, item := range aws.Prefixes {
		all = append(all, item.Prefix)
	}
	for _, item := range aws.IPv6Prefixes {
		all = append(all, item.Prefix)
	}

	var gcp struct {
		Prefixes []struct {
			IPv4 string `json:"ipv4Prefix"`
			IPv6 string `json:"ipv6Prefix"`
		} `json:"prefixes"`
	}
	if err := fetchJSON(gcpURL, &gcp); err != nil {
		return nil, err
	}
	for _, item := range gcp.Prefixes {
		all = appendNonEmpty(all, item.IPv4, item.IPv6)
	}

	azureURL, err := currentAzureURL()
	if err != nil {
		return nil, err
	}
	var azure struct {
		Values []struct {
			Properties struct {
				Prefixes []string `json:"addressPrefixes"`
			} `json:"properties"`
		} `json:"values"`
	}
	if err := fetchJSON(azureURL, &azure); err != nil {
		return nil, err
	}
	for _, value := range azure.Values {
		all = append(all, value.Properties.Prefixes...)
	}

	var oracle struct {
		Regions []struct {
			CIDRs []struct {
				CIDR string `json:"cidr"`
			} `json:"cidrs"`
		} `json:"regions"`
	}
	if err := fetchJSON(oracleURL, &oracle); err != nil {
		return nil, err
	}
	for _, region := range oracle.Regions {
		for _, item := range region.CIDRs {
			all = append(all, item.CIDR)
		}
	}

	for _, source := range []string{cloudflare4URL, cloudflare6URL} {
		data, err := fetch(source)
		if err != nil {
			return nil, err
		}
		all = append(all, strings.Fields(string(data))...)
	}

	prefixes := make([]netip.Prefix, 0, len(all))
	for _, raw := range all {
		prefix, err := netip.ParsePrefix(raw)
		if err != nil {
			return nil, fmt.Errorf("parse provider prefix %q: %w", raw, err)
		}
		prefixes = append(prefixes, prefix.Masked())
	}
	sort.Slice(prefixes, func(i, j int) bool {
		if cmp := prefixes[i].Addr().Compare(prefixes[j].Addr()); cmp != 0 {
			return cmp < 0
		}
		return prefixes[i].Bits() < prefixes[j].Bits()
	})
	normalized := prefixes[:0]
	for _, prefix := range prefixes {
		if len(normalized) > 0 && normalized[len(normalized)-1].Contains(prefix.Addr()) {
			continue
		}
		normalized = append(normalized, prefix)
	}
	return normalized, nil
}

func fetchJSON(source string, target any) error {
	data, err := fetch(source)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(data, target); err != nil {
		return fmt.Errorf("decode %s: %w", source, err)
	}
	return nil
}

func currentAzureURL() (string, error) {
	data, err := fetch(azurePage)
	if err != nil {
		return "", err
	}
	pattern := regexp.MustCompile(`https://download\.microsoft\.com/download/[^"< ]+/ServiceTags_Public_[0-9]+\.json`)
	match := pattern.Find(data)
	if match == nil {
		return "", fmt.Errorf("find Azure service-tags download")
	}
	return string(match), nil
}

func appendNonEmpty(dst []string, values ...string) []string {
	for _, value := range values {
		if value != "" {
			dst = append(dst, value)
		}
	}
	return dst
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
