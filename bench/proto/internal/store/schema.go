package store

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5"
)

// migrations are forward-only; each runs in its own transaction.
var migrations = []string{
	// 1: core schema.
	`
CREATE TABLE sites (
  id   integer PRIMARY KEY,
  host text NOT NULL UNIQUE,
  tz   text NOT NULL DEFAULT 'UTC'
);

-- D5: one random salt per (site, site-local date); purged after ~48 h.
CREATE TABLE salts (
  site_id    integer NOT NULL REFERENCES sites (id) ON DELETE CASCADE,
  day        date NOT NULL,
  salt       bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (site_id, day)
);

-- Raw events, monthly partitions on UTC ts (retention = DROP PARTITION).
-- Session dimensions are copied onto every event so page-level and
-- session-level filters need no join. No primary key: append-only.
CREATE TABLE events (
  site_id      integer     NOT NULL,
  local_date   date        NOT NULL,
  ts           timestamptz NOT NULL,
  visitor_id   bigint      NOT NULL,
  session_id   bigint      NOT NULL,
  name         text        NOT NULL,
  path         text        NOT NULL,
  source       text        NOT NULL,
  country      text        NOT NULL,
  browser      text        NOT NULL,
  os           text        NOT NULL,
  device       text        NOT NULL,
  utm_source   text,
  utm_medium   text,
  utm_campaign text,
  props        jsonb
) PARTITION BY RANGE (ts);
CREATE INDEX events_ts_brin ON events USING brin (ts) WITH (pages_per_range = 32);

-- One row per visit, batch-upserted from the in-memory cache (D8).
-- Partitioned on start_ts; the PK doubles as the per-site range index.
CREATE TABLE sessions (
  site_id       integer     NOT NULL,
  local_date    date        NOT NULL,
  start_ts      timestamptz NOT NULL,
  session_id    bigint      NOT NULL,
  visitor_id    bigint      NOT NULL,
  duration_ms   integer     NOT NULL,
  pageviews     integer     NOT NULL,
  custom_events integer     NOT NULL,
  entry_path    text        NOT NULL,
  exit_path     text        NOT NULL,
  source        text        NOT NULL,
  country       text        NOT NULL,
  browser       text        NOT NULL,
  os            text        NOT NULL,
  device        text        NOT NULL,
  utm_source    text,
  utm_medium    text,
  utm_campaign  text,
  PRIMARY KEY (site_id, start_ts, session_id)
) PARTITION BY RANGE (start_ts);
CREATE INDEX sessions_start_brin ON sessions USING brin (start_ts) WITH (pages_per_range = 32);

-- Rollups bucketed by site-local date (D4, F4). Visitors are exact per day
-- and add up across days (F1).
CREATE TABLE rollup_day (
  site_id     integer NOT NULL,
  day         date    NOT NULL,
  visitors    integer NOT NULL,
  visits      integer NOT NULL,
  pageviews   integer NOT NULL,
  bounces     integer NOT NULL,
  duration_ms bigint  NOT NULL,
  PRIMARY KEY (site_id, day)
);

-- dim: 1 path, 2 source, 3 country, 4 browser, 5 os, 6 device, 7 entry, 8 exit.
CREATE TABLE rollup_day_dim (
  site_id     integer  NOT NULL,
  dim         smallint NOT NULL,
  day         date     NOT NULL,
  value       text     NOT NULL,
  visitors    integer  NOT NULL,
  visits      integer  NOT NULL,
  pageviews   integer  NOT NULL,
  bounces     integer  NOT NULL,
  duration_ms bigint   NOT NULL,
  PRIMARY KEY (site_id, dim, day, value)
);
`,
	// 2: closed-day tables (built with the rollups when a site-local day
	// closes) and BRIN indexes that summarize themselves.
	`
-- BRIN ranges are summarized only by VACUUM unless autosummarize is on: after a
-- bulk load the old indexes held no summaries, so every "range" scan read the
-- whole partition (measured: a 2-day window scanned 4.1 GB instead of 0.3 GB).
-- Partitioned indexes can't be ALTERed, so they are recreated.
DROP INDEX events_ts_brin;
CREATE INDEX events_ts_brin ON events USING brin (ts) WITH (pages_per_range = 32, autosummarize = on);
DROP INDEX sessions_start_brin;
CREATE INDEX sessions_start_brin ON sessions USING brin (start_ts) WITH (pages_per_range = 32, autosummarize = on);

-- One dictionary for every string the closed-day tables reference (paths,
-- event names, sources, countries, browsers, OSes, devices, UTM values).
-- id 0 is '' (direct, no UTM, no entry page).
CREATE TABLE dict (
  id    integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
  value text NOT NULL UNIQUE
);
INSERT INTO dict (id, value) VALUES (0, '');

-- One row per session of a closed (site, local day), integer-encoded and
-- clustered by site within each day. Filtered queries over closed days read
-- this instead of sessions/events. Visitor-level dims (country, browser, os,
-- device) are those of the visitor-day's first session.
--   vd_n  = sessions of the visitor-day
--   flags = 1 first session of the visitor-day, 2 first with its source,
--           4 first with its entry page, 8 first with its exit page
--   seq   = the session's events in order: pageview = path_id<<2
--           | 2 (first view of the path in the session) | 1 (first in the
--           visitor-day); custom event = -name_id.
-- With the flags, "visitors" is count(*) FILTER (flag) instead of a
-- distinct-visitor aggregation whenever that is exact (see query/closed.go).
CREATE TABLE sessions_closed (
  visitor_id   bigint    NOT NULL,
  session_id   bigint    NOT NULL,  -- joins with events (props filtered by entry/exit)
  site_id      integer   NOT NULL,
  day          date      NOT NULL,
  source       integer   NOT NULL,
  country      integer   NOT NULL,
  browser      integer   NOT NULL,
  os           integer   NOT NULL,
  device       integer   NOT NULL,
  entry        integer   NOT NULL,
  exit         integer   NOT NULL,
  utm_source   integer   NOT NULL,
  utm_medium   integer   NOT NULL,
  utm_campaign integer   NOT NULL,
  pageviews    integer   NOT NULL,
  custom       integer   NOT NULL,
  duration_ms  integer   NOT NULL,
  vd_n         smallint  NOT NULL,
  flags        smallint  NOT NULL,
  seq          integer[] NOT NULL
) PARTITION BY RANGE (day);
CREATE INDEX sessions_closed_brin ON sessions_closed USING brin (site_id, day) WITH (pages_per_range = 16, autosummarize = on);

-- Daily session cube over (source, visitor-level dims). Summing cells is exact:
-- v_vd counts each visitor-day once (in the cell of its first session), v_src
-- counts it once per source it arrived from.
CREATE TABLE cube_day (
  site_id     integer NOT NULL,
  day         date    NOT NULL,
  source      integer NOT NULL,
  country     integer NOT NULL,
  browser     integer NOT NULL,
  os          integer NOT NULL,
  device      integer NOT NULL,
  v_vd        integer NOT NULL,
  v_src       integer NOT NULL,
  visits      integer NOT NULL,
  pageviews   integer NOT NULL,
  bounces     integer NOT NULL,
  duration_ms bigint  NOT NULL
) PARTITION BY RANGE (day);
CREATE INDEX cube_day_brin ON cube_day USING brin (site_id, day) WITH (pages_per_range = 8, autosummarize = on);
`,
	// 3: custom events (10% of rows) get a partial btree: prop breakdowns (F4)
	// read only their rows instead of every event of the range. Pageviews pay
	// nothing; COPY cost measured with copybench --indexes none,custom.
	`
CREATE INDEX events_custom ON events (site_id, ts) WHERE name <> 'pageview';
`,
	// 4: monthly rollups for closed months: a long-range breakdown reads one
	// row per (value, month) instead of per (value, day). Exact, because every
	// metric (visitors included, F1) adds up across days.
	`
CREATE TABLE rollup_month_dim (
  site_id     integer  NOT NULL,
  dim         smallint NOT NULL,
  month       date     NOT NULL,
  value       text     NOT NULL,
  visitors    bigint   NOT NULL,
  visits      bigint   NOT NULL,
  pageviews   bigint   NOT NULL,
  bounces     bigint   NOT NULL,
  duration_ms bigint   NOT NULL,
  PRIMARY KEY (site_id, dim, month, value)
);
-- Months whose rows are complete (all days closed and rolled up).
CREATE TABLE rollup_month_done (
  site_id integer NOT NULL,
  month   date    NOT NULL,
  PRIMARY KEY (site_id, month)
);
`,
	// 5: custom events of closed days, clustered by site within each day and
	// carrying their session's dims (dict ids). Prop breakdowns (F4) over
	// closed days read these instead of the hot events: custom events are 10%
	// of rows but spread over every heap page of events, so even the partial
	// btree of migration 3 still reads (nearly) the whole partition.
	`
CREATE TABLE custom_closed (
  visitor_id   bigint  NOT NULL,
  site_id      integer NOT NULL,
  day          date    NOT NULL,
  name         integer NOT NULL,
  path         integer NOT NULL,
  source       integer NOT NULL,
  country      integer NOT NULL,
  browser      integer NOT NULL,
  os           integer NOT NULL,
  device       integer NOT NULL,
  entry        integer NOT NULL,
  exit         integer NOT NULL,
  utm_source   integer NOT NULL,
  utm_medium   integer NOT NULL,
  utm_campaign integer NOT NULL,
  props        jsonb
) PARTITION BY RANGE (day);
CREATE INDEX custom_closed_brin ON custom_closed USING brin (site_id, day) WITH (pages_per_range = 8, autosummarize = on);
`,
	// 6: sessions_closed rows are written sorted by (site, country, visitor)
	// within each day, and the BRIN covers country (and visitor_id, for the
	// opt-in sampling mode): a country filter (the
	// most common one) reads only that country's pages instead of all of the
	// site's. Measured on stock PG 18, where every read goes through 3 io
	// workers, bytes read decide the filtered dashboard's time.
	`
DROP INDEX sessions_closed_brin;
CREATE INDEX sessions_closed_brin ON sessions_closed USING brin (site_id, day, country, visitor_id) WITH (pages_per_range = 16, autosummarize = on);
`,
	// 7: exact epoch-aligned dyadic dimension rollups. rollup_day_dim is the
	// level-0 (one-day) block; this table stores levels 1..9. The separate
	// completion marker distinguishes a completed empty block from a missing
	// block and lets queries fall back safely while ancestors are unavailable.
	`
CREATE TABLE rollup_block_dim (
  site_id     integer  NOT NULL,
  dim         smallint NOT NULL,
  level       smallint NOT NULL CHECK (level BETWEEN 1 AND 9),
  block_start date     NOT NULL,
  value       text     NOT NULL,
  visitors    bigint   NOT NULL,
  visits      bigint   NOT NULL,
  pageviews   bigint   NOT NULL,
  bounces     bigint   NOT NULL,
  duration_ms bigint   NOT NULL,
  PRIMARY KEY (site_id, dim, level, block_start, value)
);
CREATE TABLE rollup_block_done (
  site_id     integer  NOT NULL,
  level       smallint NOT NULL CHECK (level BETWEEN 0 AND 9),
  block_start date     NOT NULL,
  PRIMARY KEY (site_id, level, block_start)
);
-- Existing daily rows are complete level-0 blocks. Higher levels are rebuilt
-- explicitly by proto rollup-blocks so this migration remains short.
INSERT INTO rollup_block_done (site_id, level, block_start)
SELECT site_id, 0, day FROM rollup_day
ON CONFLICT DO NOTHING;
`,
}

// Migrate applies pending migrations.
func (s *Store) Migrate(ctx context.Context) error {
	if _, err := s.Pool.Exec(ctx, `CREATE TABLE IF NOT EXISTS schema_migrations (version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())`); err != nil {
		return err
	}
	for i, m := range migrations {
		v := i + 1
		err := pgx.BeginFunc(ctx, s.Pool, func(tx pgx.Tx) error {
			// Serialize concurrent migrators.
			if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock(7469001)`); err != nil {
				return err
			}
			var done bool
			if err := tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM schema_migrations WHERE version = $1)`, v).Scan(&done); err != nil {
				return err
			}
			if done {
				return nil
			}
			if _, err := tx.Exec(ctx, m); err != nil {
				return fmt.Errorf("migration %d: %w", v, err)
			}
			_, err := tx.Exec(ctx, `INSERT INTO schema_migrations (version) VALUES ($1)`, v)
			return err
		})
		if err != nil {
			return err
		}
	}
	return nil
}
